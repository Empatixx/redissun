/// redissun only: moves 0.23 data into Redisson's layout, up to `ARGV[2]` old entries per call. KEYS: old main, new main, timeout, idle, old last access, new last access, old options, new options. ARGV: now, batch size.
///
/// The `HSCAN` cursor is kept in the field `migrate-cursor` of the old options hash between calls. A value that unpacks as `dLc0` and fills the whole field is already in the new layout and is skipped. An old value is read with 0.23's `unwrap` and checked with 0.23's expiry rule: a live one is packed into the new main hash (where a new-layout value already there wins), an expired one is dropped from the hash and the sets. When the scan is back at `0`, the old last-access set and the old options move to their new names and the old options hash (with the cursor) is deleted. Returns how many old entries the call handled.
pub(super) static MIGRATE_FROM_0_23: LazyLock<Lua> = LazyLock::new(|| {
    Lua::from_lua(concat!(
        "local now = tonumber(ARGV[1]); ",
        "local limit = tonumber(ARGV[2]); ",
        "local inPlace = KEYS[1] == KEYS[2]; ",
        "local mainTtl = -1; ",
        "if not inPlace then ",
        "    mainTtl = redis.call('pttl', KEYS[1]); ",
        "end; ",
        "local cursor = redis.call('hget', KEYS[7], 'migrate-cursor'); ",
        "if cursor == false then cursor = '0'; end; ",
        "local handled = 0; ",
        "local finished = false; ",
        "while true do ",
        "    local page = redis.call('hscan', KEYS[1], cursor, 'count', limit); ",
        "    local entries = page[2]; ",
        "    local stopped = false; ",
        "    for i = 1, #entries, 2 do ",
        "        local field = entries[i]; ",
        "        local raw = entries[i + 1]; ",
        "        local ok, t, v, nextPos = pcall(struct.unpack, 'dLc0', raw); ",
        "        if not (ok and nextPos == #raw + 1) then ",
        "            if handled >= limit then ",
        "                stopped = true; ",
        "                break; ",
        "            end; ",
        "            local value = raw; ",
        "            local idle = 0; ",
        "            local sep = string.find(raw, ':', 1, true); ",
        "            if sep then ",
        "                value = string.sub(raw, sep + 1); ",
        "                idle = tonumber(string.sub(raw, 1, sep - 1)) or 0; ",
        "            end; ",
        "            local expires = 92233720368547758; ",
        "            local score = redis.call('zscore', KEYS[3], field); ",
        "            if score ~= false then ",
        "                expires = tonumber(score); ",
        "            end; ",
        "            if idle ~= 0 then ",
        "                local idleScore = redis.call('zscore', KEYS[4], field); ",
        "                if idleScore ~= false then ",
        "                    expires = math.min(expires, tonumber(idleScore)); ",
        "                end; ",
        "            end; ",
        "            if expires > now then ",
        "                local packed = struct.pack('dLc0', idle, string.len(value), value); ",
        "                if inPlace then ",
        "                    redis.call('hset', KEYS[2], field, packed); ",
        "                else ",
        "                    redis.call('hsetnx', KEYS[2], field, packed); ",
        "                    redis.call('hdel', KEYS[1], field); ",
        "                end; ",
        "            else ",
        "                redis.call('hdel', KEYS[1], field); ",
        "                redis.call('zrem', KEYS[3], field); ",
        "                redis.call('zrem', KEYS[4], field); ",
        "                redis.call('zrem', KEYS[5], field); ",
        "            end; ",
        "            handled = handled + 1; ",
        "        end; ",
        "    end; ",
        "    if stopped then break; end; ",
        "    cursor = page[1]; ",
        "    if cursor == '0' then ",
        "        finished = true; ",
        "        break; ",
        "    end; ",
        "    if handled >= limit then break; end; ",
        "end; ",
        "if mainTtl > 0 and redis.call('exists', KEYS[2]) == 1 then ",
        "    redis.call('pexpire', KEYS[2], mainTtl); ",
        "end; ",
        "if finished then ",
        "    if redis.call('exists', KEYS[5]) == 1 then ",
        "        if redis.call('exists', KEYS[6]) == 0 then ",
        "            redis.call('rename', KEYS[5], KEYS[6]); ",
        "        else ",
        "            redis.call('zunionstore', KEYS[6], 2, KEYS[6], KEYS[5], 'aggregate', 'max'); ",
        "            redis.call('del', KEYS[5]); ",
        "        end; ",
        "    end; ",
        "    for _, option in ipairs({'max-size', 'mode', 'has-listeners'}) do ",
        "        local setting = redis.call('hget', KEYS[7], option); ",
        "        if setting ~= false then ",
        "            redis.call('hsetnx', KEYS[8], option, setting); ",
        "        end; ",
        "    end; ",
        "    local optionsTtl = redis.call('pttl', KEYS[7]); ",
        "    if optionsTtl > 0 and redis.call('pttl', KEYS[8]) == -1 then ",
        "        redis.call('pexpire', KEYS[8], optionsTtl); ",
        "    end; ",
        "    redis.call('del', KEYS[7]); ",
        "else ",
        "    redis.call('hset', KEYS[7], 'migrate-cursor', cursor); ",
        "end; ",
        "return handled; ",
    ))
});
